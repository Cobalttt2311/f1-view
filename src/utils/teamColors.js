export function getTeamColor(teamName = "") {
  if (!teamName) return TEAM_COLORS.default;
  const clean = String(teamName)
    .toLowerCase()
    .replace(/[\s-]+/g, "_");
  for (const [key, color] of Object.entries(TEAM_COLORS)) {
    if (clean.includes(key)) return color;
  }
  return TEAM_COLORS.default;
}

export function getDriverCode(driverName = "", code = "") {
  if (code && String(code).trim().length >= 2) {
    return String(code).trim().toUpperCase();
  }
  if (!driverName) return "DRV";
  const parts = String(driverName).trim().split(/\s+/);
  const lastName = parts[parts.length - 1];
  return lastName.substring(0, 3).toUpperCase();
}

export function getDriverColor(driverCode = "", teamName = "", season = 2026) {
  const code = (driverCode || "").toUpperCase();

  // If teamName matches a known team
  if (teamName) {
    const clean = String(teamName)
      .toLowerCase()
      .replace(/[\s-]+/g, "_");
    for (const [key, color] of Object.entries(TEAM_COLORS)) {
      if (key !== "default" && clean.includes(key)) {
        return color;
      }
    }
  }

  // Check active drivers map
  if (ACTIVE_DRIVER_TEAMS[code]) {
    const teamKey = ACTIVE_DRIVER_TEAMS[code];
    return TEAM_COLORS[teamKey] || TEAM_COLORS.default;
  }

  // If historical season (< 2024) or retired driver with no current team match
  const yearNum = Number(season);
  if (yearNum && yearNum < 2024) {
    return HISTORICAL_DRIVER_COLOR;
  }

  return HISTORICAL_DRIVER_COLOR;
}
